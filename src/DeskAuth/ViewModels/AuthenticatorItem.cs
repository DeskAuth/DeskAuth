using System.ComponentModel;
using System.Runtime.CompilerServices;
using System.Windows.Media;
using DeskAuth.Core;
using DeskAuth.Services;

namespace DeskAuth.ViewModels;

/// <summary>
/// An authenticator as shown in the main list
/// </summary>
internal sealed class AuthenticatorItem : INotifyPropertyChanged
{
    /// <summary>
    /// How long an on-demand code is shown
    /// </summary>
    public static readonly TimeSpan RevealDuration = TimeSpan.FromSeconds(10);

    private const string HiddenCode = "––– –––";

    private string _code = HiddenCode;
    private double _progress;
    private bool _isCodeVisible;
    private string? _lastCode;
    private DateTimeOffset _revealStarted;
    private DateTimeOffset _revealUntil;
    private string? _revealedCode;

    public AuthenticatorItem(AuthenticatorEntry entry)
    {
        Entry = entry;
        Icon = IconLibrary.For(entry);
    }

    public event PropertyChangedEventHandler? PropertyChanged;

    /// <summary>
    /// A new code was generated by an auto-refreshing authenticator
    /// </summary>
    public event EventHandler<string>? CodeChanged;

    public AuthenticatorEntry Entry { get; }

    public string Name
    {
        get => Entry.Name;
        set
        {
            Entry.Name = value;
            OnPropertyChanged();
        }
    }

    public ImageSource? Icon { get; private set; }

    /// <summary>
    /// Code as displayed, with a space in the middle
    /// </summary>
    public string Code
    {
        get => _code;
        private set => Set(ref _code, value);
    }

    public bool IsCodeVisible
    {
        get => _isCodeVisible;
        private set
        {
            if (Set(ref _isCodeVisible, value))
            {
                OnPropertyChanged(nameof(ShowRevealButton));
                OnPropertyChanged(nameof(ShowProgress));
            }
        }
    }

    /// <summary>
    /// Fraction of the code's lifetime remaining, 0 to 1
    /// </summary>
    public double Progress
    {
        get => _progress;
        private set => Set(ref _progress, value);
    }

    public bool IsSupported => Entry.Kind != AuthenticatorKind.Unsupported;

    /// <summary>
    /// The code is shown continuously rather than when clicked
    /// </summary>
    public bool IsAutoRefresh => Entry.AutoRefresh && Entry.Kind == AuthenticatorKind.Totp && !Entry.HasPassword;

    public bool ShowRevealButton => IsSupported && !IsAutoRefresh && !IsCodeVisible;

    public bool ShowProgress => IsSupported && IsCodeVisible;

    public string? Status => Entry.Kind == AuthenticatorKind.Unsupported
        ? $"{Entry.LegacyType} authenticators are no longer supported"
        : null;

    /// <summary>
    /// Update the code and countdown
    /// </summary>
    public void Refresh(DateTimeOffset now)
    {
        if (!IsSupported)
        {
            Code = "Not supported";
            IsCodeVisible = false;
            return;
        }

        if (IsAutoRefresh && Entry.Generator is TotpGenerator totp)
        {
            string code = totp.GetCode(now);
            if (code != _lastCode)
            {
                bool first = _lastCode == null;
                _lastCode = code;
                Code = Format(code);
                if (!first)
                {
                    CodeChanged?.Invoke(this, code);
                }
            }
            Progress = totp.SecondsRemaining(now) / totp.Period;
            IsCodeVisible = true;
            return;
        }

        if (_revealedCode != null && now < _revealUntil)
        {
            // a TOTP code might roll over while it is shown
            if (Entry.Generator is TotpGenerator revealed)
            {
                _revealedCode = revealed.GetCode(now);
            }
            Code = Format(_revealedCode);
            Progress = (_revealUntil - now) / (_revealUntil - _revealStarted);
            IsCodeVisible = true;
        }
        else
        {
            if (_revealedCode != null)
            {
                _revealedCode = null;
                Entry.Lock();
            }
            Code = HiddenCode;
            IsCodeVisible = false;
        }
    }

    /// <summary>
    /// Show the code for a while. The entry must be unlocked.
    /// </summary>
    /// <returns>the code</returns>
    public string Reveal(DateTimeOffset now)
    {
        string code = Entry.GetCode(now);
        if (!IsAutoRefresh)
        {
            _revealedCode = code;
            _revealStarted = now;
            _revealUntil = now + RevealDuration;
        }
        Refresh(now);
        return code;
    }

    /// <summary>
    /// Settings that affect the display have changed
    /// </summary>
    public void SettingsChanged()
    {
        Icon = IconLibrary.For(Entry);
        _lastCode = null;
        OnPropertyChanged(string.Empty);
    }

    private static string Format(string code) => code.Length > 5 ? code.Insert(code.Length / 2, " ") : code;

    private bool Set<T>(ref T field, T value, [CallerMemberName] string? name = null)
    {
        if (EqualityComparer<T>.Default.Equals(field, value))
        {
            return false;
        }
        field = value;
        OnPropertyChanged(name);
        return true;
    }

    private void OnPropertyChanged([CallerMemberName] string? name = null) =>
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(name));
}
